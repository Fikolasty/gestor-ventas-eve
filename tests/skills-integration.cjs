'use strict';
const fs=require('node:fs'), vm=require('node:vm'), assert=require('node:assert/strict');
const html=fs.readFileSync('index.html','utf8');
const source=fs.readFileSync('src/skills_preview.html','utf8');
const shell=fs.readFileSync('src/shell.html','utf8');
const app=fs.readFileSync('src/script.js','utf8');
const build=fs.readFileSync('build.py','utf8');
const bridge=fs.readFileSync('src/skills.js','utf8');
assert.match(shell,/data-mm-module="skills"/);
assert.match(shell,/id="skillRoot"/);
assert.match(shell,/body\.mm-skills #heroIntro/);
assert.match(shell,/frame-src 'self' about:/);
assert.match(app,/SkillUI\.setPilot\(\{name:session\.name,skills:data\.skills\}\)/);
assert.match(app,/SkillUI\.setPilot\(null\)/);
assert.match(app,/SkillUI\.setLanguage\(S\.lang\)/);
assert.match(app,/sessionEpoch\+\+/);
assert.match(app,/if\(epoch!==sessionEpoch\|\|session\?\.id!==pilotId\)return/);
assert.match(app,/window\.cancelIdleCallback/);
assert.match(source,/PRICE_PAGES=4/);
assert.match(source,/pausedUntil/);
