assert.doesNotMatch(bridge,/token:|\.token\b|refresh_token|\.refresh\b/);
assert.match(bridge,/event\.source!==frame\.contentWindow/);
assert.match(build,/srcdoc|skills_doc|SKILLS_DOCUMENT/);
