assert.match(child,/skillRoot|class="wrap"/);
assert(!/<header\b/.test(child),'Skills duplicate header must be removed');
assert.match(child,/details/);
assert(!child.includes('const SKILLS_DOCUMENT='),'No recursive embedding');
const ix=html.indexOf('const SKILLS_DOCUMENT=');
const scriptStart=html.lastIndexOf('<script>',ix),scriptEnd=html.indexOf('</script>',ix);
assert(scriptStart>=0&&scriptEnd>ix);
new vm.Script(html.slice(scriptStart+8,scriptEnd),{filename:'market-moves-bundle.js'});
console.log('Skills regression: bundled scripts parse, navigation and safe character data bridge confirmed.');
