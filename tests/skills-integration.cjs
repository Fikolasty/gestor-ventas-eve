const m=html.match(/const SKILLS_DOCUMENT=("(?:\\.|[^"\\])*");/);
assert(m,'Skills HTML must be embedded in a JS string in index.html');
const child=JSON.parse(m[1]);
const cm=child.match(/<script>([\s\S]*?)<\/script>/);
assert(cm,'Embedded Skills must retain its JavaScript');
new vm.Script(cm[1],{filename:'skills-embedded.js'});
assert.match(cm[1],/mm-skills-ready/);
assert.match(cm[1],/mm-skills-pilot/);
assert.match(cm[1],/skillLevels/);
